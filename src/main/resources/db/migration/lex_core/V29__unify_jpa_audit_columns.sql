-- V29: Una sola auditoría JPA en el resto de tablas de los servicios.
-- El borrado queda en updated_at y updated_by. Se retiran deleted_at y deleted_by.

UPDATE app_user
SET status = 'DELETED'
WHERE deleted_at IS NOT NULL;

UPDATE party
SET client_status = 'INACTIVE'
WHERE deleted_at IS NOT NULL;

